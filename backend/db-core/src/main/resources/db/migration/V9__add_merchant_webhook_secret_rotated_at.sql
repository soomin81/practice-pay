-- ============================================================
-- Webhook 서명 비밀 교체에 **겹치는 기간**을 준다.
--
-- V8까지는 세대를 올리는 순간 옛 비밀이 즉시 무효였다. 그러면 가맹점이 새 비밀을
-- 자기 서버에 반영하기 전까지의 Webhook을 통째로 놓친다 — 교체가 필요한 상황
-- (비밀 노출)에서 가장 하고 싶지 않은 일이다.
--
-- **세대 컬럼을 하나 더 두지 않는다.** 세대는 1씩 올라가므로 "직전 세대"는 언제나
-- `webhook_secret_version - 1`이고, 따로 저장할 값이 아니다. 실제로 모르는 것은
-- **언제 교체했는가** 하나뿐이라 그것만 저장한다.
--
-- 이 값과 겹침 기간(애플리케이션 상수)으로 "지금 유효한 세대"를 계산한다:
--   now < rotated_at + 겹침  이면  [현재, 직전]
--   그 밖에는                      [현재]
--
-- NULL은 "한 번도 교체하지 않았다"는 뜻이다(세대 1). 기존 행과 새 가맹점이 여기
-- 해당하고, 직전 세대가 없으므로 겹칠 것도 없다 — 그래서 DEFAULT를 두지 않는다.
-- ============================================================

ALTER TABLE merchant
    ADD COLUMN webhook_secret_rotated_at DATETIME(6) NULL
        COMMENT 'Webhook 서명 비밀을 마지막으로 교체한 시각(UTC). NULL이면 교체한 적 없음. 겹침 기간 계산에 쓴다.'
        AFTER webhook_secret_version;
