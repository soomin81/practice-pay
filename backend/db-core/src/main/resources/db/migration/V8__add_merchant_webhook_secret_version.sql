-- ============================================================
-- Webhook 서명 — 가맹점별 서명 비밀의 "세대"만 저장한다.
--
-- **비밀 자체는 저장하지 않는다.** 서명 비밀은 저장된 값이 아니라
--   HMAC-SHA256(서버 Pepper, "{merchant_id}:{webhook_secret_version}")
-- 로 매번 파생한다(`HmacWebhookSigner`).
--
-- 이 시스템의 다른 자격증명(비밀번호, 초대 Token, API Key)은 전부 **검증만**
-- 하면 되므로 Hash로 저장한다. Webhook 서명 비밀은 PG가 **직접 서명하는 데
-- 써야** 해서 복원 가능해야 하는데, 그렇다고 평문 컬럼으로 두면 DB 유출이
-- 곧 전 가맹점 웹훅 위조가 된다 — 파생 방식은 DB가 통째로 새어도 Pepper가
-- 없으면 아무 비밀도 얻을 수 없다.
--
-- 그래서 이 컬럼은 비밀이 아니다(세대 번호일 뿐이라 유출돼도 무해하다).
-- 비밀이 노출됐을 때의 교체는 이 값을 1 올리는 것으로 이뤄지고, 그러면
-- 파생 입력이 달라져 이전 비밀은 즉시 무효가 된다.
--
-- 기존 행은 DEFAULT 1로 채워진다 — 아직 아무도 서명을 검증하고 있지 않아서
-- (이 마이그레이션 이전에는 서명 자체가 없었다) 세대를 나눌 이유가 없다.
-- ============================================================

ALTER TABLE merchant
    ADD COLUMN webhook_secret_version INT NOT NULL DEFAULT 1
        COMMENT 'Webhook 서명 비밀의 세대. 비밀은 저장하지 않고 이 값과 merchant_id로 파생한다. 교체 시 1 증가.'
        AFTER webhook_url;
